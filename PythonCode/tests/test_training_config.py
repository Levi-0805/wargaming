import copy
import hashlib
import json
from pathlib import Path
import sys

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'tools'))
from prepare_training_config import (prepare, POLICY_KEY, RED_MODULE, BLUE_MODULE)


@pytest.fixture
def inputs(tmp_path):
    source = tmp_path / 'platform.jsonc'
    template = tmp_path / 'published.jsonc'
    root = tmp_path / 'PythonCode'
    model = root / 'TeamAlg/FsLutk7wD2RkNgbs/Models/target_iql_v1.json'
    model.parent.mkdir(parents=True)
    model.write_bytes(b'{"numeric_policy": true}\r\n')
    raw = {
        'BaseInfo': {'AlgName': 'preserve me'},
        'config.py->GlobalConfig': dict(num_worker_threads=1, device='cpu', max_episode=10, seed=10098,
            AlgorithmConfig_Red=RED_MODULE + '.py->AlgorithmConfig',
            AlgorithmConfig_Blue=BLUE_MODULE + '.py->AlgorithmConfig'),
        'Common.cssim_env_wrapper.py->ScenarioConfig': dict(MaxStepsPerEpisode=500, StepGameTime=.5,
            TimeDilation=1, render=True, Enable_Reward_Sharing=False, TcpAddr='127.0.0.1', CSSIMPort=21051,
            Algorithm_Names=[m + '->ReinforceAgentAlgorithm' for m in (RED_MODULE, BLUE_MODULE)]),
        'unrelated': {'nested': [1, 'kept', False]},
    }
    policy = dict(mode='hybrid_iql', iql_model='Models/target_iql_v1.json', iql_shadow=False,
                  enable_continuous_column=False)
    source.write_text(json.dumps(raw), encoding='utf-8')
    template.write_text(json.dumps({POLICY_KEY: policy}), encoding='utf-8')
    return source, template, root, raw, policy, tmp_path / 'logs/batch/effective.json'


def run(inputs):
    source, template, root, _, _, output = inputs
    return prepare(source, output, template=template, pythoncode_root=root)


def test_preparation_preserves_source_and_other_fields_and_records_exact_hashes(inputs):
    source, template, root, raw, policy, output = inputs
    old_bytes = source.read_bytes()
    result = run(inputs)
    effective = json.loads(output.read_bytes())
    assert source.read_bytes() == old_bytes
    assert {k: v for k, v in effective.items() if k != POLICY_KEY} == raw
    assert effective[POLICY_KEY] == {**policy, 'iql_model': result['model']}
    assert Path(result['model']).is_absolute()
    for name, path in [('source', source), ('template', template), ('effective', output), ('model', Path(result['model']))]:
        assert result[name + '_sha256'] == hashlib.sha256(path.read_bytes()).hexdigest()
    assert len(result['changes']) == len(policy)
    assert all(not item['before_present'] for item in result['changes'])
    assert Path(result['provenance_path']).is_file()


@pytest.mark.parametrize('section,key,bad', [
    ('GlobalConfig', 'device', 'cuda'), ('GlobalConfig', 'max_episode', 1),
    ('GlobalConfig', 'num_worker_threads', True), ('GlobalConfig', 'seed', '10098'),
    ('ScenarioConfig', 'MaxStepsPerEpisode', 200), ('ScenarioConfig', 'StepGameTime', 1),
    ('ScenarioConfig', 'TimeDilation', 2), ('ScenarioConfig', 'render', 1),
    ('ScenarioConfig', 'Enable_Reward_Sharing', True),
    ('ScenarioConfig', 'Algorithm_Names', [BLUE_MODULE+'->ReinforceAgentAlgorithm', RED_MODULE+'->ReinforceAgentAlgorithm']),
    ('GlobalConfig', 'AlgorithmConfig_Blue', RED_MODULE+'.py->AlgorithmConfig'),
])
def test_user_setting_mismatch_is_rejected_without_output(inputs, section, key, bad):
    source, _, _, raw, _, output = inputs
    data = copy.deepcopy(raw)
    next(v for k, v in data.items() if k.endswith('->' + section))[key] = bad
    source.write_text(json.dumps(data), encoding='utf-8')
    with pytest.raises(ValueError):
        run(inputs)
    assert not output.exists()


def test_existing_overrides_and_comments_are_preserved_except_explicit_injection(inputs):
    source, _, _, raw, _, output = inputs
    alternate = POLICY_KEY.replace('.py->', '->')
    raw[alternate] = dict(mode='rule', learning_rate=.001, enable_parent_assignment=False)
    source.write_text('// Generated by UE\n'+json.dumps(raw), encoding='utf-8-sig')
    result = run(inputs)
    effective = json.loads(output.read_bytes())
    assert POLICY_KEY not in effective
    assert effective[alternate]['mode'] == 'hybrid_iql'
    assert effective[alternate]['learning_rate'] == .001
    assert effective[alternate]['enable_parent_assignment'] is False
    changed_mode = next(c for c in result['changes'] if c['path'][1] == 'mode')
    assert changed_mode['before'] == 'rule' and changed_mode['before_present']


def test_ambiguous_platform_sections_rejected(inputs):
    source, _, _, raw, _, _ = inputs
    raw['other->GlobalConfig'] = raw['config.py->GlobalConfig']
    source.write_text(json.dumps(raw), encoding='utf-8')
    with pytest.raises(ValueError, match='exactly one'):
        run(inputs)


@pytest.mark.parametrize('changes', [dict(iql_shadow=True), dict(mode='rule'),
                                    dict(enable_entry_waves='false'), dict(unexpected=True),
                                    dict(iql_model='../../escape.json')])
def test_invalid_template_is_rejected(inputs, changes):
    _, template, _, _, policy, output = inputs
    template.write_text(json.dumps({POLICY_KEY: {**policy, **changes}}), encoding='utf-8')
    with pytest.raises(ValueError):
        run(inputs)
    assert not output.exists()


def test_no_overwriting_inputs_or_previous_batch(inputs):
    source, template, root, _, _, _ = inputs
    with pytest.raises(ValueError, match='overwrite an input'):
        prepare(source, source, template=template, pythoncode_root=root)
    run(inputs)
    with pytest.raises(ValueError, match='already exists'):
        run(inputs)
