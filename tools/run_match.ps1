param(
    [string]$CssimRoot = '',
    [int]$TimeoutMinutes = 20,
    [switch]$NoLaunch
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot

function Resolve-CssimRoot {
    param([string]$Requested)
    if (-not [string]::IsNullOrWhiteSpace($Requested) -and (Test-Path -LiteralPath (Join-Path $Requested 'Client'))) {
        return $Requested
    }
    foreach ($candidate in @('C:\CSSIM', 'E:\CSSIM')) {
        if (Test-Path -LiteralPath (Join-Path $candidate 'Client')) {
            return $candidate
        }
    }
    throw 'CSSIM installation not found. Pass -CssimRoot.'
}

function Start-IfMissing {
    param(
        [Parameter(Mandatory = $true)][string]$ProcessName,
        [Parameter(Mandatory = $true)][string]$Exe,
        [Parameter(Mandatory = $true)][string]$Work
    )
    if (Get-Process -Name $ProcessName -ErrorAction SilentlyContinue) {
        Write-Host "Already running: $ProcessName"
        return
    }
    if (-not (Test-Path -LiteralPath $Exe)) {
        throw "Executable not found: $Exe"
    }
    $windowStyle = if ($ProcessName -eq 'Server') { 'Hidden' } else { 'Normal' }
    Start-Process -FilePath $Exe -WorkingDirectory $Work -WindowStyle $windowStyle | Out-Null
    Write-Host "Started $ProcessName"
}

$CssimRoot = Resolve-CssimRoot -Requested $CssimRoot
$outputDir = Join-Path $CssimRoot 'Server\CSSIM\Saved\Output'
$python = Join-Path $CssimRoot 'Client\Data\AlgData\PythonEnv\python.exe'
$parser = Join-Path $repoRoot 'tools\parse_match_score.py'
$protocolDir = Join-Path $CssimRoot 'Client\Data\AlgData\PythonCode\logs'
$resultsDir = Join-Path $repoRoot 'results\matches'
New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
New-Item -ItemType Directory -Path $resultsDir -Force | Out-Null

function Assert-SourceVersion {
    $status = & git -C $repoRoot status --porcelain -- PythonCode
    if ($LASTEXITCODE -ne 0 -or $status) { throw 'Algorithm source must be clean before recording a versioned match.' }
    $head = & git -C $repoRoot rev-parse HEAD
    if ($LASTEXITCODE -ne 0) { throw 'Cannot determine algorithm source commit.' }
    $files = & git -C $repoRoot -c core.quotepath=false ls-files -- PythonCode
    if ($LASTEXITCODE -ne 0) { throw 'Cannot enumerate versioned source files.' }
    foreach ($file in $files) {
        # TaskConfig may be regenerated by UE; compare the versioned executable
        # code and team configuration, not runtime-generated session settings.
        if ($file -like 'PythonCode/TaskConfig/*') { continue }
        $expected = (Get-FileHash -LiteralPath (Join-Path $repoRoot $file) -Algorithm SHA256).Hash
        foreach ($side in @('Client', 'Server')) {
            $copy = Join-Path $CssimRoot ($side + '\Data\AlgData\' + $file)
            if (-not (Test-Path -LiteralPath $copy) -or
                (Get-FileHash -LiteralPath $copy -Algorithm SHA256).Hash -ne $expected) {
                throw "Deployed source differs from Git: $copy. Publish before recording a match."
            }
        }
    }
    return ($head -join '').Trim()
}

function Get-MatchFiles {
    Get-ChildItem -LiteralPath $outputDir -Filter 'Output_*.txt' -ErrorAction SilentlyContinue
    Get-ChildItem -LiteralPath $protocolDir -Directory -ErrorAction SilentlyContinue | ForEach-Object {
        Get-Item -LiteralPath (Join-Path $_.FullName 'protocol.jsonl') -ErrorAction SilentlyContinue
    }
}

$sourceCommit = Assert-SourceVersion
$startedAt = Get-Date
# Snapshot before launch so a rapidly created output is not mistaken for an old run.
$known = @{}
Get-MatchFiles | ForEach-Object { $known[$_.FullName] = $true }
if (-not $NoLaunch) {
    Start-IfMissing -ProcessName 'Server' -Exe (Join-Path $CssimRoot 'Server\Server\Server.exe') -Work (Join-Path $CssimRoot 'Server\Server')
    Start-Sleep -Seconds 2
    Start-IfMissing -ProcessName 'CSSIMClient-Win64-Shipping' -Exe (Join-Path $CssimRoot 'Client\CSSIM\Binaries\Win64\CSSIMClient-Win64-Shipping.exe') -Work (Join-Path $CssimRoot 'Client\CSSIM\Binaries\Win64')
    Write-Host 'CSSIM client is open. In the client, start the same scenario as before (red: FsLutk7wD2RkNgbs). This script waits for the score file.'
}

$deadline = $startedAt.AddMinutes($TimeoutMinutes)

$summaryPath = $null
while ((Get-Date) -lt $deadline) {
    $candidates = Get-MatchFiles |
        Where-Object { -not $known.ContainsKey($_.FullName) -and $_.Length -gt 1000 -and $_.LastWriteTime -ge $startedAt.AddSeconds(-2) } |
        Sort-Object LastWriteTime -Descending
    foreach ($file in $candidates) {
        $stableFor = (Get-Date) - $file.LastWriteTime
        if ($stableFor.TotalSeconds -lt 8) { continue }
        $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $summaryPath = Join-Path $resultsDir "$stamp.json"
        & $python $parser $file.FullName --out $summaryPath --source-commit $sourceCommit
        $parseExit = $LASTEXITCODE
        $summary = if ($parseExit -in @(0, 2) -and (Test-Path -LiteralPath $summaryPath)) {
            Get-Content -LiteralPath $summaryPath -Raw -Encoding UTF8 | ConvertFrom-Json
        } else { $null }
        $terminalPackets = ($null -ne $summary -and $summary.rounds.Count -gt 0 -and
            $summary.rounds[-1].score_packets_complete -and $summary.malformed_json_lines.Count -eq 0)
        if ($parseExit -eq 0 -or $terminalPackets) {
            if ((Assert-SourceVersion) -ne $sourceCommit) {
                throw 'Source changed during the match; refusing to attach a misleading version.'
            }
            Copy-Item -LiteralPath $summaryPath -Destination (Join-Path $repoRoot 'results\latest.json') -Force
            if (-not $summary.complete) {
                Write-Warning 'Terminal scores retained with unknown side attribution; no score is guessed.'
            }
            Write-Host "Match recorded: $summaryPath"
            exit 0
        }
        Remove-Item -LiteralPath $summaryPath -Force -ErrorAction SilentlyContinue
    }
    Start-Sleep -Seconds 5
}

Write-Host "No finished match score appeared within $TimeoutMinutes minutes."
exit 2
